-- CRM administrativo-comercial: apenas vendas/negociações remuneradas.
-- Projetos internos NÃO exigem cliente; parcerias externas gratuitas ficam separadas.
-- Migração ADITIVA; não altera projetos, Forms, Drive ou contratos legados.

create or replace function app_private.can_manage_crm()
returns boolean language sql stable security definer set search_path = ''
as $$
  select auth.uid() is not null
     and coalesce((app_private.current_profile() ->> 'cargo') in ('diretoria','adm'), false)
     and public.dw43_not_revoked();
$$;

create table if not exists public.crm_clientes (
  id bigint generated by default as identity primary key,
  nome text not null check (length(btrim(nome)) > 1),
  tipo_pessoa text not null default 'pj' check (tipo_pessoa in ('pf','pj')),
  cpf_cnpj text,
  segmento text,
  cidade text,
  uf text,
  observacoes text,
  historico_legado boolean not null default false,
  cliente_desde date,
  status text not null default 'ativo' check (status in ('ativo','inativo','encerrado')),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.crm_contatos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.crm_clientes(id) on delete cascade,
  nome text not null check (length(btrim(nome)) > 0),
  cargo text,
  email text,
  telefone text,
  principal boolean not null default false,
  criado_em timestamptz not null default now()
);

create table if not exists public.crm_negociacoes (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.crm_clientes(id) on delete restrict,
  titulo text not null check (length(btrim(titulo)) > 1),
  natureza text not null default 'prestacao' check (natureza in ('prestacao','parceria')),
  modalidade_financeira text not null default 'remunerada' check (modalidade_financeira = 'remunerada'),
  status text not null default 'prospeccao'
    check (status in ('prospeccao','em_negociacao','proposta_enviada','aceita','perdida','concluida')),
  responsavel_dubworks text,
  escopo text,
  observacoes text,
  proxima_acao_em date,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- Registros externos gratuitos não contam como clientes ou vendas no CRM.
create table if not exists public.crm_parcerias_gratuitas (
  id bigint generated by default as identity primary key,
  nome_parceiro text not null check (length(btrim(nome_parceiro)) > 1),
  natureza text not null default 'parceria' check (natureza in ('parceria','prestacao')),
  responsavel_dubworks text,
  contato_nome text,
  contato_email text,
  contato_telefone text,
  escopo text,
  observacoes text,
  status text not null default 'rascunho'
    check (status in ('rascunho','formalizando','ativa','encerrada')),
  historico_legado boolean not null default false,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.crm_servicos (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  unidade text not null default 'projeto'
    check (unidade in ('minuto','episodio','corte','hora','projeto','unidade')),
  preco_referencia numeric(14,2) not null default 0 check (preco_referencia >= 0),
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

create table if not exists public.crm_propostas (
  id bigint generated by default as identity primary key,
  negociacao_id bigint not null references public.crm_negociacoes(id) on delete restrict,
  versao integer not null default 1 check (versao > 0),
  titulo text not null,
  descricao_escopo text,
  modo_preco text not null default 'automatico' check (modo_preco in ('automatico','personalizado')),
  valor_referencia numeric(14,2) not null default 0 check (valor_referencia >= 0),
  valor_negociado numeric(14,2) not null default 0 check (valor_negociado >= 0),
  custo_interno_estimado numeric(14,2) check (custo_interno_estimado >= 0),
  justificativa_valor text,
  condicoes_pagamento text,
  validade_em date,
  status text not null default 'rascunho'
    check (status in ('rascunho','em_revisao','aprovada','enviada','aceita','recusada','cancelada')),
  aprovado_por text,
  aprovado_em timestamptz,
  arquivo_url text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint crm_propostas_versao_uniq unique (negociacao_id, versao)
);

create table if not exists public.crm_proposta_itens (
  id bigint generated by default as identity primary key,
  proposta_id bigint not null references public.crm_propostas(id) on delete cascade,
  servico_id bigint references public.crm_servicos(id) on delete set null,
  descricao text not null,
  unidade text not null default 'projeto',
  quantidade numeric(12,3) not null default 1 check (quantidade > 0),
  preco_unitario numeric(14,2) not null default 0 check (preco_unitario >= 0),
  criado_em timestamptz not null default now()
);

create table if not exists public.crm_contratos (
  id bigint generated by default as identity primary key,
  negociacao_id bigint references public.crm_negociacoes(id) on delete restrict,
  parceria_gratuita_id bigint references public.crm_parcerias_gratuitas(id) on delete restrict,
  versao integer not null default 1 check (versao > 0),
  titulo text not null,
  objeto_escopo text,
  arquivo_url text,
  tipo_modelo text not null
    check (tipo_modelo in ('servico_gratuito','servico_remunerado','parceria_gratuita','parceria_remunerada')),
  status text not null default 'rascunho'
    check (status in ('rascunho','em_revisao','aprovado','enviado','aguardando_assinatura','assinado','cancelado')),
  assinaturas_confirmadas_em timestamptz,
  responsavel_aprovacao text,
  observacoes text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint crm_contratos_contraparte check (
    (negociacao_id is not null and parceria_gratuita_id is null)
    or (negociacao_id is null and parceria_gratuita_id is not null)
  ),
  constraint crm_contratos_assinado_com_arquivo check (
    status <> 'assinado' or (arquivo_url is not null and length(btrim(arquivo_url)) > 4 and assinaturas_confirmadas_em is not null)
  )
);

-- Um projeto interno continua SEM cliente/negociação. Vinculação só se houver venda.
alter table public.projetos
  add column if not exists crm_negociacao_id bigint
  references public.crm_negociacoes(id) on delete set null;

create index if not exists crm_negociacoes_cliente_idx on public.crm_negociacoes(cliente_id);
create index if not exists crm_contatos_cliente_idx on public.crm_contatos(cliente_id);
create index if not exists crm_propostas_negociacao_idx on public.crm_propostas(negociacao_id);
create index if not exists crm_contratos_negociacao_idx on public.crm_contratos(negociacao_id);
create index if not exists crm_propostas_status_idx on public.crm_propostas(status);

-- Comercial é restrito a Diretoria e ADM na camada de banco, além da interface.
do $ddl$
declare tabela text;
begin
  foreach tabela in array array[
    'crm_clientes','crm_contatos','crm_negociacoes',
    'crm_parcerias_gratuitas','crm_servicos','crm_propostas',
    'crm_proposta_itens','crm_contratos'
  ] loop
    execute format('alter table public.%I enable row level security', tabela);
    execute format('revoke all on public.%I from anon', tabela);
    execute format('grant select,insert,update on public.%I to authenticated', tabela);
    execute format('drop policy if exists crm_acesso_select on public.%I', tabela);
    execute format('drop policy if exists crm_acesso_insert on public.%I', tabela);
    execute format('drop policy if exists crm_acesso_update on public.%I', tabela);
    execute format('create policy crm_acesso_select on public.%I for select to authenticated using ((select app_private.can_manage_crm()))', tabela);
    execute format('create policy crm_acesso_insert on public.%I for insert to authenticated with check ((select app_private.can_manage_crm()))', tabela);
    execute format('create policy crm_acesso_update on public.%I for update to authenticated using ((select app_private.can_manage_crm())) with check ((select app_private.can_manage_crm()))', tabela);
    execute format('grant usage, select on sequence public.%I to authenticated', tabela || '_id_seq');
  end loop;
end $ddl$;

comment on table public.crm_clientes is
  'Somente clientes de negociações remuneradas; projetos internos e parcerias externas gratuitas não exigem registro de cliente';
comment on table public.crm_parcerias_gratuitas is
  'Formalização documental de parcerias gratuitas fora do funil de vendas';
