-- Novo gerenciamento de semanas/cortes por episódio.
-- NÃO altera/renumera projeto_semanas nem registros legados de elenco e entregas.
-- Aplicar somente no fluxo de migrações após testes em ambiente isolado.

create table if not exists public.episodio_cortes (
  id bigint generated by default as identity primary key,
  projeto_id bigint not null references public.projetos(id) on delete cascade,
  episodio_id bigint not null references public.projeto_episodios(id) on delete cascade,
  semana integer not null check (semana > 0),
  duracao_segundos integer not null check (duracao_segundos between 1 and 86400),
  status text not null default 'nao_iniciada'
    check (status in ('nao_iniciada', 'em_andamento', 'pausada', 'concluida')),
  motivo_pausa text,
  observacao text,
  prazo_em timestamptz,
  video_base_url text,
  trilha_url text,
  criado_por text,
  atualizado_por text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint episodio_cortes_por_episodio_semana unique (episodio_id, semana),
  constraint episodio_cortes_pausa_exige_motivo
    check (status <> 'pausada' or length(btrim(coalesce(motivo_pausa,''))) > 0)
);

create index if not exists episodio_cortes_projeto_episodio_idx
on public.episodio_cortes (projeto_id, episodio_id, semana);

-- Garantia mesmo para escrita por service_role: o episódio é do mesmo projeto
-- e não é uma subdivisão/semana preexistente da interface antiga.
create or replace function public.dw_validar_episodio_corte()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.projeto_episodios ep
     where ep.id = new.episodio_id
       and ep.projeto_id = new.projeto_id
       and ep.parent_id is null
  ) then
    raise exception 'O episódio não pertence ao projeto ou não é um episódio principal'
      using errcode = '23514';
  end if;
  new.atualizado_em := now();
  return new;
end;
$$;

drop trigger if exists dw_validar_episodio_corte_tr on public.episodio_cortes;
create trigger dw_validar_episodio_corte_tr
before insert or update on public.episodio_cortes
for each row execute function public.dw_validar_episodio_corte();

alter table public.episodio_cortes enable row level security;
revoke all on public.episodio_cortes from anon;
grant select, insert, update on public.episodio_cortes to authenticated;
grant usage, select on sequence public.episodio_cortes_id_seq to authenticated;

drop policy if exists episodio_cortes_leitura on public.episodio_cortes;
create policy episodio_cortes_leitura on public.episodio_cortes
for select to authenticated
using (
  (select public.dw43_not_revoked())
  and app_private.can_view_project_by_id(projeto_id)
);

drop policy if exists episodio_cortes_inclusao on public.episodio_cortes;
create policy episodio_cortes_inclusao on public.episodio_cortes
for insert to authenticated
with check (
  (select public.dw43_not_revoked())
  and exists (
    select 1 from public.projetos p
    where p.id = projeto_id
      and app_private.can_update_project(p.lider, p.editor)
  )
);

drop policy if exists episodio_cortes_edicao on public.episodio_cortes;
create policy episodio_cortes_edicao on public.episodio_cortes
for update to authenticated
using (
  (select public.dw43_not_revoked())
  and exists (
    select 1 from public.projetos p
    where p.id = projeto_id
      and app_private.can_update_project(p.lider, p.editor)
  )
)
with check (
  (select public.dw43_not_revoked())
  and exists (
    select 1 from public.projetos p
    where p.id = projeto_id
      and app_private.can_update_project(p.lider, p.editor)
  )
);

-- Vínculo explícito opcional, SEM tentar adivinhar associação a partir de
-- textos legados como 'Semana 01'.
alter table public.entregas_producao
add column if not exists episodio_corte_id bigint
references public.episodio_cortes(id) on delete set null;

create index if not exists entregas_producao_corte_idx
on public.entregas_producao (episodio_corte_id)
where episodio_corte_id is not null;

-- Impede anexar a um corte de outro projeto ou episódio.
create or replace function public.dw_validar_entrega_episodio_corte()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if new.episodio_corte_id is not null and not exists (
    select 1 from public.episodio_cortes c
     where c.id = new.episodio_corte_id
       and c.projeto_id = new.projeto_id
       and c.episodio_id = new.episodio_id
  ) then
    raise exception 'A entrega deve pertencer ao mesmo projeto e episódio do corte'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

drop trigger if exists dw_validar_entrega_corte_tr on public.entregas_producao;
create trigger dw_validar_entrega_corte_tr
before insert or update of episodio_corte_id, episodio_id, projeto_id
on public.entregas_producao
for each row execute function public.dw_validar_entrega_episodio_corte();

comment on table public.episodio_cortes is
  'Semana = um corte de duração real por episódio; projeto_semanas antigo preservado para migração supervisionada';
comment on column public.entregas_producao.episodio_corte_id is
  'Referência explícita ao corte da semana; nunca preencher por inferência ambígua do texto da resposta';
